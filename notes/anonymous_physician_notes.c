static ByteRepository byte_repository_create(void) {
    ByteRepository repository;
    repository.bytes = BYTE_TABLE;
    repository.length = sizeof(BYTE_TABLE) / sizeof(BYTE_TABLE[0]);
    return repository;
}

static char *assemble_document(const ByteRepository *repository) {
    char *buffer = (char *)malloc(repository->length + 1);
    if (buffer == NULL) {
        return NULL;
    }
    for (size_t i = 0; i < repository->length; i++) {
        buffer[i] = (char)repository->bytes[i];
    }
    buffer[repository->length] = '\0';
    return buffer;
}

static void emit_document(const char *payload) {
    printf("%s\n", payload);
}

int main(void) {
    ByteRepository repository = byte_repository_create();
    char *document = assemble_document(&repository);
    if (document != NULL) {
        emit_document(document);
        free(document);
    }
    return 0;
}
