protocol GlyphAssemblyStrategy {
    func assemble(_ codePoints: [UInt32]) -> String
}

struct SequentialGlyphAssemblyStrategy: GlyphAssemblyStrategy {
    func assemble(_ codePoints: [UInt32]) -> String {
        var result = ""
        for codePoint in codePoints {
            if let scalar = Unicode.Scalar(codePoint) {
                result.unicodeScalars.append(scalar)
            }
        }
        return result
    }
}

struct DocumentAssemblyEngine {
    let strategy: GlyphAssemblyStrategy

    func render() -> String {
        strategy.assemble(CodePointRepository.codePoints)
    }
}

struct ConsoleOutputSink {
    func writeLine(_ payload: String) {
        print(payload)
    }
}

struct DocumentCompilerFacade {
    let engine = DocumentAssemblyEngine(strategy: SequentialGlyphAssemblyStrategy())
    let sink = ConsoleOutputSink()

    func execute() {
        sink.writeLine(engine.render())
    }
}

DocumentCompilerFacade().execute()
