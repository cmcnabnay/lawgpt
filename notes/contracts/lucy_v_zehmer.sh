glyph_assembly_strategy__assemble() {
    local -a bytes=("$@")
    local byte
    local escaped=""
    local assembled
    for byte in "${bytes[@]}"; do
        escaped+="\\$(printf '%03o' "$byte")"
    done
    printf -v assembled '%b' "$escaped"
    printf '%s' "$assembled"
}

