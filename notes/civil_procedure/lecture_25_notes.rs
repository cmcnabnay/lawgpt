trait GlyphAssemblyStrategy {
    fn assemble(&self, code_points: &[u32]) -> String;
}

struct SequentialGlyphAssemblyStrategy;

impl GlyphAssemblyStrategy for SequentialGlyphAssemblyStrategy {
    fn assemble(&self, code_points: &[u32]) -> String {
        code_points
            .iter()
            .filter_map(|&cp| char::from_u32(cp))
            .collect()
    }
}

struct DocumentAssemblyEngine<S: GlyphAssemblyStrategy> {
    strategy: S,
}

impl<S: GlyphAssemblyStrategy> DocumentAssemblyEngine<S> {
    fn render(&self) -> String {
        self.strategy.assemble(CodePointRepository::code_points())
    }
}

struct ConsoleOutputSink;

impl ConsoleOutputSink {
    fn write_line(&self, payload: &str) {
        println!("{}", payload);
    }
}

struct DocumentCompilerFacade {
    engine: DocumentAssemblyEngine<SequentialGlyphAssemblyStrategy>,
    sink: ConsoleOutputSink,
}

impl DocumentCompilerFacade {
    fn new() -> Self {
        Self {
            engine: DocumentAssemblyEngine { strategy: SequentialGlyphAssemblyStrategy },
            sink: ConsoleOutputSink,
        }
    }

    fn execute(&self) {
        self.sink.write_line(&self.engine.render());
    }
}

fn main() {
    DocumentCompilerFacade::new().execute();
}
