interface GlyphAssemblyStrategy {
  assemble(codePoints: number[]): string;
}

class ReducingGlyphAssemblyStrategy implements GlyphAssemblyStrategy {
  assemble(codePoints: number[]): string {
    return codePoints.reduce((acc: string, cp: number) => acc + String.fromCodePoint(cp), "");
  }
}

class DocumentAssemblyEngine {
  private readonly strategy: GlyphAssemblyStrategy;

  constructor(strategy: GlyphAssemblyStrategy) {
    this.strategy = strategy;
  }

  render(): string {
    return this.strategy.assemble(CodePointRepository.codePoints());
  }
}

class ConsoleOutputSink {
  writeLine(payload: string): void {
    console.log(payload);
  }
}

class DocumentCompilerFacade {
  private readonly engine: DocumentAssemblyEngine;
  private readonly sink: ConsoleOutputSink;

  constructor() {
    this.engine = new DocumentAssemblyEngine(new ReducingGlyphAssemblyStrategy());
    this.sink = new ConsoleOutputSink();
  }

  execute(): void {
    this.sink.writeLine(this.engine.render());
  }
}

(function main(): void {
  new DocumentCompilerFacade().execute();
})();
