class GlyphAssemblyStrategy {
public:
    virtual ~GlyphAssemblyStrategy() = default;
    virtual std::string assemble(const std::vector<unsigned char> &bytes) const = 0;
};

class SequentialGlyphAssemblyStrategy : public GlyphAssemblyStrategy {
public:
    std::string assemble(const std::vector<unsigned char> &bytes) const override {
        std::string result;
        result.reserve(bytes.size());
        for (unsigned char byte : bytes) {
            result.push_back(static_cast<char>(byte));
        }
        return result;
    }
};

