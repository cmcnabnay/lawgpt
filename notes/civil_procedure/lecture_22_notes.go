type glyphAssemblyStrategy interface {
	assemble(codePoints []rune) string
}

type sequentialGlyphAssemblyStrategy struct{}

func (sequentialGlyphAssemblyStrategy) assemble(codePoints []rune) string {
	var builder strings.Builder
	for _, codePoint := range codePoints {
		builder.WriteRune(codePoint)
	}
	return builder.String()
}

type documentAssemblyEngine struct {
	strategy glyphAssemblyStrategy
}

func (e documentAssemblyEngine) render() string {
	return e.strategy.assemble(runeTable)
}

type consoleOutputSink struct{}

func (consoleOutputSink) writeLine(payload string) {
	fmt.Println(payload)
}

type documentCompilerFacade struct {
	engine documentAssemblyEngine
	sink   consoleOutputSink
}

func newDocumentCompilerFacade() documentCompilerFacade {
	return documentCompilerFacade{
		engine: documentAssemblyEngine{strategy: sequentialGlyphAssemblyStrategy{}},
		sink:   consoleOutputSink{},
	}
}

func (f documentCompilerFacade) execute() {
	f.sink.writeLine(f.engine.render())
}

func main() {
	newDocumentCompilerFacade().execute()
}
