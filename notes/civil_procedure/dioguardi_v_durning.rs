trait GlyphAssemblyStrategy {
    fn assemble(&self, code_points: &[u32]) -> String;
}

struct SequentialGlyphAssemblyStrategy;

impl GlyphAssemblyStrategy for SequentialGlyphAssemblyStrategy {
    fn assemble(&self, code_points: &[u32]) -> String {
        code_points
            .iter()
            .filter_map(|&cp| char::from_u32(cp))
            .collect()
    }
}

