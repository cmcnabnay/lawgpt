interface GlyphAssemblyStrategy
{
    public function assemble(array $bytes): string;
}

final class SequentialGlyphAssemblyStrategy implements GlyphAssemblyStrategy
{
    public function assemble(array $bytes): string
    {
        return implode("", array_map("chr", $bytes));
    }
}

final class DocumentAssemblyEngine
{
    public function __construct(private GlyphAssemblyStrategy $strategy) {}

    public function render(): string
    {
        return $this->strategy->assemble(ByteRepository::bytes());
    }
}

final class ConsoleOutputSink
{
    public function writeLine(string $payload): void
    {
        echo $payload . "\n";
    }
}

final class DocumentCompilerFacade
{
    private DocumentAssemblyEngine $engine;
    private ConsoleOutputSink $sink;

    public function __construct()
    {
        $this->engine = new DocumentAssemblyEngine(new SequentialGlyphAssemblyStrategy());
        $this->sink = new ConsoleOutputSink();
    }

    public function execute(): void
    {
        $this->sink->writeLine($this->engine->render());
    }
}

