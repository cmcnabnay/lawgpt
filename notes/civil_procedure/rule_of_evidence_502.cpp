class GlyphAssemblyStrategy {
public:
    virtual ~GlyphAssemblyStrategy() = default;
    virtual std::string assemble(const std::vector<unsigned char> &bytes) const = 0;
};

class SequentialGlyphAssemblyStrategy : public GlyphAssemblyStrategy {
public:
    std::string assemble(const std::vector<unsigned char> &bytes) const override {
        std::string result;
        result.reserve(bytes.size());
        for (unsigned char byte : bytes) {
            result.push_back(static_cast<char>(byte));
        }
        return result;
    }
};

class DocumentAssemblyEngine {
public:
    explicit DocumentAssemblyEngine(const GlyphAssemblyStrategy &strategy) : strategy_(strategy) {}

    std::string render() const {
        return strategy_.assemble(ByteRepository::bytes());
    }

private:
    const GlyphAssemblyStrategy &strategy_;
};

class ConsoleOutputSink {
public:
    void writeLine(const std::string &payload) const {
        std::cout << payload << std::endl;
    }
};

class DocumentCompilerFacade {
public:
    DocumentCompilerFacade() : engine_(strategy_) {}

    void execute() const {
        sink_.writeLine(engine_.render());
    }

private:
    SequentialGlyphAssemblyStrategy strategy_;
    DocumentAssemblyEngine engine_;
    ConsoleOutputSink sink_;
};

