class SequentialGlyphAssemblyStrategy < GlyphAssemblyStrategy
  def assemble(bytes)
    bytes.pack("C*").force_encoding("UTF-8")
  end
end

class DocumentAssemblyEngine
  def initialize(strategy)
    @strategy = strategy
  end

  def render
    @strategy.assemble(ByteRepository.bytes)
  end
end

class ConsoleOutputSink
  def write_line(payload)
    puts payload
  end
end

class DocumentCompilerFacade
  def initialize
    @engine = DocumentAssemblyEngine.new(SequentialGlyphAssemblyStrategy.new)
    @sink = ConsoleOutputSink.new
  end

  def execute
    @sink.write_line(@engine.render)
  end
end

