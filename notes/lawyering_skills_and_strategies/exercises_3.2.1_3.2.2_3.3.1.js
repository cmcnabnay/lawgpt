class GlyphAssemblyStrategy {
  assemble(_codePoints) {
    throw new Error("GlyphAssemblyStrategy.assemble must be overridden");
  }
}

class ReducingGlyphAssemblyStrategy extends GlyphAssemblyStrategy {
  assemble(codePoints) {
    return codePoints.reduce((acc, cp) => acc + String.fromCodePoint(cp), "");
  }
}

class DocumentAssemblyEngine {
  constructor(strategy) {
    this.strategy = strategy;
  }

  render() {
    return this.strategy.assemble(CodePointRepository.codePoints());
  }
}

class ConsoleOutputSink {
  writeLine(payload) {
    console.log(payload);
  }
}

class DocumentCompilerFacade {
  constructor() {
    this.engine = new DocumentAssemblyEngine(new ReducingGlyphAssemblyStrategy());
    this.sink = new ConsoleOutputSink();
  }

  execute() {
    this.sink.writeLine(this.engine.render());
  }
}

